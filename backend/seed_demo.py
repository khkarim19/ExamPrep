def seed():
    conn = db()
    conn.execute("DELETE FROM progress")
    conn.execute("DELETE FROM problems")
    conn.execute("DELETE FROM theory_sections")
    conn.execute("DELETE FROM tasks")
    for i, (title, theory, problems, drills) in enumerate(TOPICS, 1):
        cur = conn.execute(
            "INSERT INTO tasks (title, sort_order) VALUES (?, ?)", (title, i))
        tid = cur.lastrowid
        sections = SECTIONS_OVERRIDE.get(i, [("Основы", theory, None)])
        ids = []
        for n, (st, sc, _) in enumerate(sections, 1):
            ids.append(conn.execute(
                "INSERT INTO theory_sections (task_id, title, content_md, sort_order) VALUES (?, ?, ?, ?)",
                (tid, st, sc, n)).lastrowid)
        for sid, (_, _, parent_idx) in zip(ids, sections):
            if parent_idx is not None:
                conn.execute("UPDATE theory_sections SET parent_id = ? WHERE id = ?",
                             (ids[parent_idx], sid))
        rows = [(tid, "example", q, a,
                 EXPLANATIONS.get((i, "example", n), f"**Ответ:** {a}"), n)
                for n, (q, a) in enumerate(problems, 1)]
        rows += [(tid, "practice", q, a, EXPLANATIONS.get((i, "practice", n), ""), n)
                 for n, (q, a) in enumerate(drills, 1)]
        conn.executemany(
            "INSERT INTO problems (task_id, kind, statement_md, solution_md, explanation_md, sort_order) "
            "VALUES (?, ?, ?, ?, ?, ?)", rows)
    conn.commit()
    conn.close()
    print(f"seeded {len(TOPICS)} tasks")


if __name__ == "__main__":
    seed()
